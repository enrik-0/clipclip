import { randomBytes } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import type { DeploymentMode } from "@paperclipai/shared";
import { updateEnvFileContents, writeEnvFileAtomicallyIfChanged } from "@paperclipai/shared/env-file";

const JWT_SECRET_ENV_KEY = "PAPERCLIP_AGENT_JWT_SECRET";

export type LocalAgentJwtSecretResult =
  | { status: "skipped" | "present" }
  | { status: "created"; envFilePath: string }
  | { status: "unsaved"; envFilePath: string; error: unknown };

/**
 * Agent runs need a signing secret to receive `PAPERCLIP_API_KEY`. Without
 * one, a local trusted instance still starts, and every request an agent makes
 * without a bearer counts as the board user, so the agent acts as that person.
 * `paperclipai onboard` and `worktree init` write the secret, but a plain
 * `pnpm dev` start does not.
 *
 * In local trusted mode, create the secret on the first start and save it in
 * the instance env file (the one `onboard` writes), so later starts keep the
 * same secret. Other modes keep requiring an explicit secret.
 */
export function ensureLocalTrustedAgentJwtSecret(input: {
  env: NodeJS.ProcessEnv;
  envFilePath: string;
  deploymentMode: DeploymentMode;
}): LocalAgentJwtSecretResult {
  const { env, envFilePath, deploymentMode } = input;
  if (deploymentMode !== "local_trusted") return { status: "skipped" };
  // `jwtConfig()` also accepts BETTER_AUTH_SECRET.
  if (env[JWT_SECRET_ENV_KEY]?.trim() || env.BETTER_AUTH_SECRET?.trim()) return { status: "present" };

  const secret = randomBytes(32).toString("hex");
  env[JWT_SECRET_ENV_KEY] = secret;
  try {
    const previous = existsSync(envFilePath) ? readFileSync(envFilePath, "utf8") : null;
    const next = updateEnvFileContents(
      previous ?? "# Paperclip environment variables\n# Generated by the Paperclip server\n\n",
      { [JWT_SECRET_ENV_KEY]: secret },
      { valueEncoding: "minimal" },
    );
    writeEnvFileAtomicallyIfChanged(envFilePath, previous, next);
    return { status: "created", envFilePath };
  } catch (error) {
    // This process can still sign run tokens; the next start makes a new secret.
    return { status: "unsaved", envFilePath, error };
  }
}
